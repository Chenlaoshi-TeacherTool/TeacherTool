'use strict';

/*
 * One-off generator: reads the existing hardcoded preset question banks and
 * emits a SQL script that inserts them into the `question_banks` / `questions`
 * tables from database/schema.sql.
 *
 * Usage: node database/generate-question-banks-backfill.js > database/backfill-question-banks.sql
 */

const path = require('path');
const presetQuestionBanks = require(path.join(__dirname, '..', 'src', 'teachingTools', 'data', 'preset-questionbanks.js'));

function sqlString(value) {
  if (value === null || value === undefined) return 'NULL';
  return `N'${String(value).replace(/'/g, "''")}'`;
}

function sqlJson(value) {
  return `N'${JSON.stringify(value).replace(/'/g, "''")}'`;
}

const lines = [];
lines.push('-- Generated by database/generate-question-banks-backfill.js — do not edit by hand.');
lines.push('-- Backfills question_banks / questions from src/teachingTools/data/preset-questionbanks.js');
lines.push('');

for (const bank of presetQuestionBanks) {
  lines.push('BEGIN TRANSACTION;');
  lines.push('INSERT INTO question_banks (slug, name, description, theme, level, curriculum)');
  lines.push(
    `VALUES (${sqlString(bank.id)}, ${sqlString(bank.name)}, ${sqlString(bank.description)}, ` +
      `${sqlString(bank.theme)}, ${sqlString(bank.level)}, ${sqlString(bank.curriculum)});`
  );
  lines.push('DECLARE @bankId INT = SCOPE_IDENTITY();');

  bank.questions.forEach((question, index) => {
    lines.push(
      'INSERT INTO questions (bank_id, external_id, theme_zh, level_code, type_code, prompt, answer, note, options, tags, sort_order) VALUES ' +
        `(@bankId, ${sqlString(question.id)}, ${sqlString(question.theme)}, ${sqlString(question.level)}, ` +
        `${sqlString(question.type)}, ${sqlString(question.prompt)}, ${sqlString(question.answer)}, ` +
        `${sqlString(question.note)}, ${sqlJson(question.options || [])}, ${sqlJson(question.tags || [])}, ${index});`
    );
  });

  lines.push('COMMIT TRANSACTION;');
  lines.push('GO');
  lines.push('');
}

process.stdout.write(lines.join('\n') + '\n');
