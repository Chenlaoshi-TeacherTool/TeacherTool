'use strict';

/*
 * One-off generator: reads the existing hardcoded preset word lists and emits
 * a SQL script that inserts them into the `word_lists` / `word_list_items`
 * tables from database/schema.sql. Run once against a fresh Azure SQL
 * database, then retire once the admin CMS can manage this content directly.
 *
 * Usage: node database/generate-word-lists-backfill.js > database/backfill-word-lists.sql
 */

const path = require('path');
const presetWordLists = require(path.join(__dirname, '..', 'src', 'teachingTools', 'data', 'preset-wordlists.js'));

function sqlString(value) {
  if (value === null || value === undefined) return 'NULL';
  return `N'${String(value).replace(/'/g, "''")}'`;
}

const lines = [];
lines.push('-- Generated by database/generate-word-lists-backfill.js — do not edit by hand.');
lines.push('-- Backfills word_lists / word_list_items from src/teachingTools/data/preset-wordlists.js');
lines.push('');

for (const list of presetWordLists) {
  lines.push('BEGIN TRANSACTION;');
  lines.push('INSERT INTO word_lists (slug, name, description, theme, level, curriculum, owner_user_id)');
  lines.push(
    `VALUES (${sqlString(list.id)}, ${sqlString(list.name)}, ${sqlString(list.description)}, ` +
      `${sqlString(list.theme)}, ${sqlString(list.level)}, ${sqlString(list.curriculum)}, NULL);`
  );
  lines.push('DECLARE @listId INT = SCOPE_IDENTITY();');

  list.items.forEach((item, index) => {
    lines.push(
      'INSERT INTO word_list_items (list_id, zh, py, en, img_blob_url, note, sort_order) VALUES ' +
        `(@listId, ${sqlString(item.zh)}, ${sqlString(item.py)}, ${sqlString(item.en)}, NULL, NULL, ${index});`
    );
  });

  lines.push('COMMIT TRANSACTION;');
  lines.push('GO');
  lines.push('');
}

process.stdout.write(lines.join('\n') + '\n');
