'use strict';

/*
 * One-off generator: reads the existing hardcoded tool guides and articles
 * and emits a SQL script that inserts them into the `tool_guides` /
 * `articles` tables from database/schema.sql.
 *
 * Usage: node database/generate-site-content-backfill.js > database/backfill-site-content.sql
 */

const path = require('path');
const { toolGuides, articles } = require(path.join(__dirname, '..', 'src', 'teachingTools', 'data', 'site-content.js'));

function sqlString(value) {
  if (value === null || value === undefined) return 'NULL';
  return `N'${String(value).replace(/'/g, "''")}'`;
}

function sqlJson(value) {
  if (value === null || value === undefined) return 'NULL';
  return `N'${JSON.stringify(value).replace(/'/g, "''")}'`;
}

const lines = [];
lines.push('-- Generated by database/generate-site-content-backfill.js — do not edit by hand.');
lines.push('-- Backfills tool_guides / articles from src/teachingTools/data/site-content.js');
lines.push('');

for (const slug of Object.keys(toolGuides)) {
  const guide = toolGuides[slug];
  lines.push(
    'INSERT INTO tool_guides (slug, title, eyebrow, grades, duration, summary, what_it_is, example_title, example, app_url, steps, tips) VALUES ' +
      `(${sqlString(slug)}, ${sqlString(guide.title)}, ${sqlString(guide.eyebrow)}, ${sqlString(guide.grades)}, ` +
      `${sqlString(guide.duration)}, ${sqlString(guide.summary)}, ${sqlString(guide.whatItIs)}, ` +
      `${sqlString(guide.exampleTitle)}, ${sqlString(guide.example)}, ${sqlString(guide.appUrl || null)}, ` +
      `${sqlJson(guide.steps || [])}, ${sqlJson(guide.tips || [])});`
  );
}
lines.push('GO');
lines.push('');

for (const article of articles) {
  lines.push(
    'INSERT INTO articles (slug, category, title, description, read_time, intro, sections, related_tool_label, related_tool_href) VALUES ' +
      `(${sqlString(article.slug)}, ${sqlString(article.category)}, ${sqlString(article.title)}, ` +
      `${sqlString(article.description)}, ${sqlString(article.readTime)}, ${sqlJson(article.intro || [])}, ` +
      `${sqlJson(article.sections || [])}, ${sqlString(article.relatedTool ? article.relatedTool.label : null)}, ` +
      `${sqlString(article.relatedTool ? article.relatedTool.href : null)});`
  );
}
lines.push('GO');
lines.push('');

process.stdout.write(lines.join('\n') + '\n');
